MAJORS = [m for m, _, _ in TAX]
MINOR_OF = {s: m for m, _, subs in TAX for s, _, _ in subs}  # 细类 → 大类


def labels() -> list[str]:
    return MAJORS + list(MINOR_OF)


def tax_text() -> str:
    """给打标 prompt 看的品类表：每个大类一行，列出细类。"""
    return "\n".join(f"- {m}：" + "、".join(s for s, _, _ in subs) for m, _, subs in TAX)


def std_value(pairs: list[tuple[str, str]]) -> str:
    """[(大类, 细类)] → "|大类|细类|…|"。细类可以为空。"""
    out = []
    for m, s in pairs:
        for x in (m, s):
            if x and x not in out:
                out.append(x)
    return "|" + "|".join(out) + "|" if out else ""


def _clean(w: str) -> str:
    return re.sub(r"[\\^$.|?*+()\[\]{}]", "", w)


def _words(xs):
    out = []
    for x in xs:
        x = _clean(x)
        if len(x) >= 2 and x not in out:  # 单字词不进兜底（"面"会撞上"面包"）
            out.append(x)
    return out


# 查询时一并带上的相关细类：广东人说"粤菜"一般也包括潮汕菜、客家菜；说"甜品"也要冰淇淋
EXPAND = {"粤菜": ["潮汕菜", "客家菜"], "甜品": ["冰淇淋"], "酒吧": ["居酒屋"]}  # 大类、细类都可以带


def query_map() -> dict:
    """CODE_MERGE 内联这份：{"w": {查询词: [[节点…], [菜名同义词…]]}, "t": {节点: [店名/高德品类兜底词]}}。

    同一个词同时是大类和细类的同义词时（"快餐""沙拉"），按先出现的大类算。
    品类词只比店名和高德品类，不比推荐菜（"美式"会撞上推荐菜里的"美式咖啡"）；菜名才比推荐菜。
    菜名在表里可以写成一组同义说法（"意面=意粉=pasta"），说其中任一个都按整组匹配。
    """
    w, t = {}, {}

    def put(word, nodes, dishes):
        k = word.lower()
        if k and k not in w:
            w[k] = [nodes, _words(dishes)]

    for m, msyn, subs in TAX:
        t[m] = _words([m] + msyn + [x for s, ssyn, _ in subs for x in [s] + ssyn])
        for s, ssyn, _ in subs:
            t[s] = _words([s] + ssyn)
        for x in [m] + msyn:
            put(x, [m] + EXPAND.get(m, []), [])
    for m, _, subs in TAX:
        for s, ssyn, _ in subs:
            for x in [s] + ssyn:
                put(x, [s] + EXPAND.get(s, []), [])
    for m, _, subs in TAX:
        for s, _, dishes in subs:
            for d in dishes:
                group = d.split("=")
                for x in group:
                    put(x, [s], group)
    return {"w": w, "t": t}


def query_res(kw, qm):
    """查询词 → (cate_re, name_re, dish_re, dish_w, kb_w)。CODE_MERGE 构建时直接内联这个函数的源码（只用 re，别引用模块里的别的东西）。

    SQL 召回的品类命中 kw_hit 分两级（flow_code.SQL_RECALL）：
    - 1 级：std_cate 命中 cate_re（标准品类节点，说大类就命中全部细类）；没打标准品类的店，店名或高德品类命中 name_re（同义词展开）；
    - 菜名（dish_re）命中店名或推荐菜：用户说的是菜名时算 2 级（dish_w=2），排在只是同品类的店前面；说的是品类词时 dish_re 是原词，算 1 级；
    - 跨店检索（KB-review）前 5 名按 kb_w 算级别：点名菜时 2（评价里写了这道菜，和推荐菜里写了一样算数），表外词时 1，
      只说品类节点时 0（评价里顺口提一句"比西餐好"的店不能算西餐）。
    打了标的店只认标准品类和原词，"盖饭"这类同义词不会把中式快餐算成日料。
    复合词（"烧肉丼饭""炒牛杂拌川"）取包含的所有词的并集；表里一个词都没有的退回原词子串匹配。
    """
    kw = (kw or "").strip()
    k0 = kw.lower()
    hits = [qm["w"][k0]] if k0 in qm["w"] else []
    if not hits and k0:
        ks = [k for k in qm["w"] if len(k) >= 2 and k in k0]
        ks = [k for k in ks if not any(k != o and k in o for o in ks)]  # 只留最长的，"拉面"在"日式拉面"里就不单算
        hits = [qm["w"][k] for k in sorted(ks)]

    def alt(ws):
        ws = [re.sub(r"[^0-9a-zA-Z一-鿿 ]", "", x) for x in ws]
        out = []
        for x in ws:
            if x and x not in out:
                out.append(x)
        return "(" + "|".join(out) + ")" if out else "a^"  # a^ 永不命中

    raw = re.sub(r"[^0-9a-zA-Z一-鿿 ]", "", kw)
    if not kw:
        return "^", "^", "^", "1", "0"  # 没说品类：全部算命中
    if not hits:
        return "a^", alt([raw]), alt([raw]), "1", "1"
    nodes = [n for h in hits for n in h[0]]
    dishes = [d for h in hits for d in h[1]]
    if dishes:
        return "[|]" + alt(nodes) + "[|]", alt(dishes), alt(dishes), "2", "2"
    names = [x for n in nodes for x in qm["t"].get(n, [])] + ([raw] if len(raw) >= 2 else [])
    return "[|]" + alt(nodes) + "[|]", alt(names), alt([raw] if len(raw) >= 2 else []), "1", "0"


